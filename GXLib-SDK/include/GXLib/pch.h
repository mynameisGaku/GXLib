#pragma once
/// @file pch.h
/// @brief プリコンパイルドヘッダー（全部入り・後方互換）
///
/// 【初学者向け解説】
/// プリコンパイルドヘッダー（PCH）とは、よく使うヘッダーファイルを
/// 事前にコンパイルしておくことで、ビルド時間を短縮する仕組みです。
/// Windows.hやDirectX 12のヘッダーは巨大なので、PCHに入れると効果的です。
/// すべての.cppファイルはこのpch.hを最初にインクルードします。
///
/// このファイルは pch_common.h + pch_graphics.h + pch_audio.h の統合版です。
/// モジュール分割後は各サブライブラリが個別のPCHを使用しますが、
/// Compat層や既存コードはこの全部入りPCHを継続使用します。

// ============================================================================
// グラフィックス (Windows + STL + D3D12 + DirectXMath + DirectWrite/D2D)
// ============================================================================
#include "pch_graphics.h"

// ============================================================================
// オーディオ (XAudio2 + X3DAudio)
// ============================================================================
#include <xaudio2.h>
#include <x3daudio.h>
#pragma comment(lib, "xaudio2.lib")
